const RARITIES = Object.freeze({ c: 'Common', u: 'Uncommon', r: 'Rare', e: 'Epic', s: 'Showcase' });
const ART_VARIANTS = Object.freeze({ n: 'Normal', a: 'Alternate Art', o: 'Overnumbered', u: 'Ultimate' });
const SET_TOTALS = Object.freeze({ OGN: 298, OGS: 24, SFD: 221, UNL: 219, VEN: 166 });

function clean(value) {
  return String(value ?? '').trim().toUpperCase().replace(/[★☆]/g, '*').replace(/-STAR\b/g, '*').replace(/\s+/g, '-');
}

function openRiftPrintingKey(value, fallbackSetCode = '') {
  const raw = clean(value);
  const fallback = clean(fallbackSetCode).match(/^(OGN|OGS|SFD|UNL|VEN)$/)?.[1] || '';
  const prefixed = raw.match(/(?:^|\b)(OGN|OGS|SFD|UNL|VEN)-((?:SP|R|T)?\d+[A-Z]?)(\*)?/);
  if (prefixed) {
    const denominator = Number(raw.match(/\/(\d+)/)?.[1] || 0);
    const expectedDenominator = prefixed[2].startsWith('SP') ? 6 : SET_TOTALS[prefixed[1]];
    if (denominator && denominator !== expectedDenominator) return '';
    return `${prefixed[1]}-${prefixed[2]}${prefixed[3] || ''}`;
  }
  const unprefixed = raw.match(/^((?:SP|R|T)?\d+[A-Z]?)(\*)?(?:\/\d+)?(?:-|$)/);
  if (!fallback || !unprefixed) return '';
  const denominator = Number(raw.match(/\/(\d+)/)?.[1] || 0);
  const expectedDenominator = unprefixed[1].startsWith('SP') ? 6 : SET_TOTALS[fallback];
  if (denominator && denominator !== expectedDenominator) return '';
  return `${fallback}-${unprefixed[1]}${unprefixed[2] || ''}`;
}

function lookupOpenRiftPrinting(value, fallbackSetCode = '') {
  const key = openRiftPrintingKey(value, fallbackSetCode);
  const packed = PRINTINGS[key];
  if (!packed) return null;
  const rarity = RARITIES[packed[0]] || '';
  const artVariant = ART_VARIANTS[packed[1]] || '';
  const signed = packed[2] === '1';
  const collectorTreatments = [
    ...(artVariant === 'Normal' ? [] : [artVariant]),
    ...(signed ? ['Signature'] : [])
  ];
  const collectorTreatment = signed ? 'Signature' : (collectorTreatments[0] || '');
  return {
    key,
    rarity,
    artVariant,
    signed,
    collectorTreatment,
    collectorTreatments,
    source: 'OpenRift exact collector-number catalog',
    sourceUrl: OPENRIFT_CATALOG_URL,
    snapshotDate: OPENRIFT_SNAPSHOT_DATE
  };
}

